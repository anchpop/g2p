#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnknownPhoneme(pub String);
impl fmt::Display for UnknownPhoneme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "unrecognized phoneme token {:?}", self.0)
    }
}
impl<'de> serde::Deserialize<'de> for Phoneme {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let token = <String as serde::Deserialize>::deserialize(deserializer)?;
        token.parse().map_err(serde::de::Error::custom)
    }
}
impl std::error::Error for UnknownPhoneme {}
impl fmt::Display for Phoneme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}
impl AsRef<str> for Phoneme {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}
impl Borrow<str> for Phoneme {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn inventory_round_trips_and_rejects_nonphones() {
        for &phone in Phoneme::ALL {
            assert_eq!(phone.as_str().parse::<Phoneme>().unwrap(), phone);
            let json = serde_json::to_string(&phone).unwrap();
            assert_eq!(serde_json::from_str::<Phoneme>(&json).unwrap(), phone);
        }
        for invalid in ["<pad>", "|", "??", "d[", "a1", "made-up"] {
            assert!(invalid.parse::<Phoneme>().is_err());
        }
    }
}
